#!/usr/bin/env python
"""gen_uplay_proxy.py - generate src/uplay_proxy/uplay_proxy.cpp + .def (32-bit MSVC).

Proxy for uplay_r1_loader.dll: UPLAY_* cdecl exports -> naked stack-forwarding
logging thunks (extern "C"). Real DLL loaded from <bindir>\\real\\uplay_r1_loader.dll.
Log file: <bindir>\\uplay_api.log. C string quotes are inserted via qh(); log lines
end with %c argument 10 (never a literal newline inside a C string literal).
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXJ = os.path.join(ROOT, "local", "scratch", "loader_exports.json")
OUTD = os.path.join(ROOT, "src", "uplay_proxy")
os.makedirs(OUTD, exist_ok=True)

def qh(s):
    """escape double quotes for embedding inside a C string literal emit."""
    return s.replace(chr(34), chr(92) + chr(34))

data = json.load(open(EXJ))
names = [e["name"] for e in data["uplay_r1_loader.dll"]["exports"] if e["name"]]
cdecls = [n for n in names if n.startswith("UPLAY_")]
others = [n for n in names if not n.startswith("UPLAY_")]

# Orbit-API gates forced to return 1 when env FC3COOP_FAKE_PARTY is set (int(void) cdecl, ABI-safe).
# Only zero-arg bool gates are faked; member-list / session calls stay forwarded (struct layout unsafe).
FAKE_ONE = {"UPLAY_USER_IsConnected", "UPLAY_PARTY_IsInParty", "UPLAY_PARTY_IsPartyLeader"}

L = []
def emit(*lines):
    for l in lines:
        L.append(l)

BIGFMT = "[%02d:%02d:%02d.%03d] t%u #%lu %-45s a=%08x %08x %08x %08x %08x %08x %08x %08x from %s ret=%d (0x%x)%c"
ATTFMT = "===== uplay_proxy attach pid=%u%c"
UPFMT = "proxy up: real=%p exports=%d missing=%d fake=%d%c"

emit("// uplay_proxy.cpp - GENERATED by scripts/gen_uplay_proxy.py. DO NOT EDIT.",
"#define WIN32_LEAN_AND_MEAN",
"#include <windows.h>",
"#include <stdio.h>",
"#include <string.h>",
"#include <stdlib.h>",
"",
"static const char BSB[2] = {92, 0};",
"static CRITICAL_SECTION g_cs;",
"static FILE* g_log = NULL;",
"static volatile LONG g_seq = 0;",
"static char g_exe[64] = " + chr(34) + "FC3.exe" + chr(34) + ";",
"static HMODULE g_real = NULL;",
"#define NEXP " + str(len(names)),
"static void* g_realp[NEXP];",
"static const char* g_names[NEXP] = {")
for n in names:
    emit(chr(34) + n + chr(34) + ",")
fakeinit = "{" + ",".join(("1" if n in FAKE_ONE else "0") for n in names) + "}"
emit("};",
"static int g_fakeval[NEXP] = " + fakeinit + ";",
"static int g_fake = 0;",
"static int g_logpump = 0;",
"",
"static void logOpen(void) {",
"    if (g_log) return;",
"    InitializeCriticalSection(&g_cs);",
"    char base[MAX_PATH]; GetModuleFileNameA(NULL, base, MAX_PATH);",
"    char* s = strrchr(base, 92); if (s) *s = 0;",
"    char path[MAX_PATH]; sprintf(path, " + chr(34) + "%s" + chr(34) + " " + chr(34) + "%suplay_api.log" + chr(34) + ", base, BSB);",
"    g_log = fopen(path, " + chr(34) + "a" + chr(34) + ");",
"    if (g_log) { fprintf(g_log, " + chr(34) + ATTFMT + chr(34) + ", GetCurrentProcessId(), 10); fflush(g_log); }",
"}",
"static void describe(DWORD addr, char* out, size_t cb) {",
"    (void)cb;",
"    out[0] = 0;",
"    HMODULE h = NULL;",
"    if (addr) {",
"        __try {",
"            if (!GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT, (LPCSTR)addr, &h)) h = NULL;",
"        } __except (EXCEPTION_EXECUTE_HANDLER) { h = NULL; }",
"    }",
"    if (!h) { sprintf(out, " + chr(34) + "0x%x" + chr(34) + ", addr); return; }",
"    char path[MAX_PATH] = {0};",
"    __try {",
"        if (GetModuleFileNameA(h, path, MAX_PATH)) { char* b = strrchr(path, 92); strcpy(path, b ? b + 1 : path); } else strcpy(path, " + chr(34) + "?" + chr(34) + ");",
"    } __except (EXCEPTION_EXECUTE_HANDLER) { strcpy(path, " + chr(34) + "?" + chr(34) + "); }",
"    DWORD rva = addr - (DWORD)h;",
"    char tag[96] = {0};",
"    if (_stricmp(path, g_exe) == 0 || strstr(path, " + chr(34) + "FC3" + chr(34) + ") != NULL) {",
"        if      (rva == 0x00cf6790) strcpy(tag, " + chr(34) + " [RVCreateGameSession]" + chr(34) + ");",
"        else if (rva == 0x00cf6690) strcpy(tag, " + chr(34) + " [RVJoinGameSession]" + chr(34) + ");",
"        else if (rva >= 0x010620400u && rva < 0x010623500u) strcpy(tag, " + chr(34) + " [party-glue-region]" + chr(34) + ");",
"        else if (rva == 0x0113409d0) strcpy(tag, " + chr(34) + " [LOADER-FUN_113409d0]" + chr(34) + ");",
"    }",
"    sprintf(out, " + chr(34) + "%s+0x%x%s" + chr(34) + ", path, rva, tag);",
"}",
"",
"int __cdecl log_entry(int slot, void** argp, DWORD retaddr);",
"int __cdecl log_entry(int slot, void** argp, DWORD retaddr) {",
"    DWORD a[8] = {0,0,0,0,0,0,0,0};",
"    __try { for (int i = 0; i < 8; i++) a[i] = (DWORD)argp[i]; } __except (EXCEPTION_EXECUTE_HANDLER) {}",
"    const char* nm = (slot >= 0 && slot < NEXP) ? g_names[slot] : " + chr(34) + "?" + chr(34) + ";",
"    if (!g_logpump && (nm[0] && (_stricmp(nm, " + chr(34) + "UPLAY_Update" + chr(34) + ") == 0 || _stricmp(nm, " + chr(34) + "UPLAY_GetNextEvent" + chr(34) + ") == 0))) return 0;",
"    int fk = (g_fake && slot >= 0 && slot < NEXP) ? g_fakeval[slot] : 0;",
"    char d[170]; describe(retaddr, d, sizeof(d));",
"    if (fk) { strcat(d, " + chr(34) + " [FAKE]" + chr(34) + "); }",
"    if (g_log) {",
"        EnterCriticalSection(&g_cs);",
"        SYSTEMTIME st; GetLocalTime(&st);",
"        fprintf(g_log, " + chr(34) + BIGFMT + chr(34) + ",",
"            st.wHour, st.wMinute, st.wSecond, st.wMilliseconds, GetCurrentThreadId(),",
"            (unsigned long)InterlockedIncrement(&g_seq), nm,",
"            a[0],a[1],a[2],a[3],a[4],a[5],a[6],a[7], d, fk, fk, 10);",
"        fflush(g_log);",
"        LeaveCriticalSection(&g_cs);",
"    }",
"    return 0;",
"}",
"",
"// SAFE thunks for ALL exports: log on entry under pushfd/pushad (regs+flags restored), then TAIL-CALL the real export (jmp, exact ABI for any calling convention) or, for the 3 gate fakes, return 1. Never re-call the real fn with fabricated args.")
for k in range(len(names)):
    fk = names[k] in FAKE_ONE
    tail = ["  mov eax, 1", "  ret"] if fk else ["  mov eax, dword ptr [g_rawp_%d]" % k, "  jmp eax"]
    lines = ["static void* g_rawp_%d;" % k,
             'extern "C" void __declspec(naked) th_%d(void){ __asm {' % k,
             "  pushfd",
             "  pushad",
             "  lea  eax, [esp+40]        // &first caller arg",
             "  mov  edx, [esp+36]        // caller return address",
             "  push edx                  // arg3: retaddr",
             "  push eax                  // arg2: argp",
             "  push %d                   // arg1: slot" % k,
             "  call log_entry",
             "  add  esp, 12",
             "  popad",
             "  popfd"] + tail + ["} }"]
    emit(*lines)
emit("",
"static void resolveReal(void) {",
"    BYTE* img = (BYTE*)g_real;",
"    PIMAGE_DOS_HEADER dos = (PIMAGE_DOS_HEADER)img;",
"    if (dos->e_magic != IMAGE_DOS_SIGNATURE) return;",
"    PIMAGE_NT_HEADERS nt = (PIMAGE_NT_HEADERS)(img + dos->e_lfanew);",
"    if (nt->Signature != IMAGE_NT_SIGNATURE) return;",
"    PIMAGE_EXPORT_DIRECTORY ex = (PIMAGE_EXPORT_DIRECTORY)(img + nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_EXPORT].VirtualAddress);",
"    DWORD* nms = (DWORD*)(img + ex->AddressOfNames);",
"    WORD* ords = (WORD*)(img + ex->AddressOfNameOrdinals);",
"    DWORD* funcs = (DWORD*)(img + ex->AddressOfFunctions);",
"    for (DWORD i = 0; i < ex->NumberOfNames; i++) {",
"        const char* nm = (const char*)(img + nms[i]);",
"        int j; for (j = 0; j < NEXP; j++) if (strcmp(g_names[j], nm) == 0) break;",
"        if (j < NEXP) g_realp[j] = (void*)(img + funcs[ords[i]]);",
"    }",
"}",
"static void wireRaw(void){")
for k in range(len(names)):
    emit("  g_rawp_%d = g_realp[%d];" % (k, k))
emit("}",
"",
"BOOL WINAPI DllMain(HINSTANCE h, DWORD reason, LPVOID rsv) {",
"    (void)rsv;",
"    if (reason == DLL_PROCESS_ATTACH) {",
"        DisableThreadLibraryCalls(h);",
"        logOpen();",
"        g_fake = (getenv(" + chr(34) + "FC3COOP_FAKE_PARTY" + chr(34) + ") != NULL) ? 1 : 0;",
"        g_logpump = (getenv(" + chr(34) + "FC3COOP_LOG_PUMP" + chr(34) + ") != NULL) ? 1 : 0;",
"        char exe[MAX_PATH]; GetModuleFileNameA(NULL, exe, MAX_PATH);",
"        char* b = strrchr(exe, 92); if (b) strcpy(g_exe, b + 1);",
"        char self[MAX_PATH]; GetModuleFileNameA(h, self, MAX_PATH);",
"        char* s = strrchr(self, 92);",
"        if (s) sprintf(s + 1, " + chr(34) + "real%suplay_r1_loader.dll" + chr(34) + ", BSB);",
"        g_real = LoadLibraryExA(self, NULL, LOAD_WITH_ALTERED_SEARCH_PATH);",
"        if (!g_real) g_real = LoadLibraryA(self);",
"        if (g_real) { resolveReal(); wireRaw(); }",
"        EnterCriticalSection(&g_cs);",
"        if (g_log) {",
"            int miss = 0; for (int i = 0; i < NEXP; i++) if (!g_realp[i]) miss++;",
"            fprintf(g_log, " + chr(34) + UPFMT + chr(34) + ", g_real, NEXP, miss, g_fake, 10); fflush(g_log);",
"        }",
"        LeaveCriticalSection(&g_cs);",
"    }",
"    return TRUE;",
"}")

def_lines = ["LIBRARY uplay_r1_loader", "EXPORTS"]
for i, n in enumerate(names):
    def_lines.append("  %s = th_%d" % (n, i))

open(os.path.join(OUTD, "uplay_proxy.cpp"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
open(os.path.join(OUTD, "uplay_proxy.def"), "w", encoding="utf-8", newline="\n").write("\n".join(def_lines) + "\n")
print("generated: cdecl:", len(cdecls), "raw:", len(others), "lines:", len(L))
