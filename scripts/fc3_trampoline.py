#!/usr/bin/env python
# fc3_trampoline.py - safe, reversible test of "can 1.06 run a quick-launch command line?"
#
# WHY THIS EXISTS
# `bin/farcry3_d3d11.exe` (203816 B, stub sha256 5437b2e37a54f8a3b28c342f2b2670ca907fd60bc74905b0b7527f69bafc965e)
# is a DRM stub: it resolves the canonical install exe from HKLM and re-executes it with ONLY
# `-language=<lang>`, dropping every other argument (NOTES.md "The exe is a DRM stub"). Therefore the
# verified 1.06 quick-launch switches (-host/-login/-coop/-online/-ip) never reach the game.
# This tool creates one of two reversible workarounds so the owner can test whether 1.06 accepts them:
#   A) trampoline   - rename the real stub to farcry3_d3d11.stub.exe and put a small python launcher at
#                     the original name that re-executes the renamed stub WITH the quick-launch arguments.
#   B) reg file     - write a .reg that redirects HKLM ...\Ubisoft\Far Cry 3 ExecutableName to the renamed
#                     stub (needs to be merged as administrator; the tool only WRITES the file, it does not
#                     touch the registry).
# Nothing here is destructive: every action prints what it will do first, backs the original file next to
# it as <name>.bak with its sha256 recorded, and `uninstall` restores byte-exact content.
#
# SAFETY
# - Only `install` writes anything, and only inside the game `bin` folder you pass with --game-dir.
# - `reg` mode never writes the registry: it emits a .reg file for the owner to review/merge.
# - `uninstall` refuses to run unless the .bak it created exists and hashes to the recorded stub hash.
# - The original stub must be verified afterwards: Ubisoft Connect may re-download it ("verifying files").

import argparse, hashlib, os, shutil, sys

STUB_SHA256 = "5437b2e37a54f8a3b28c342f2b2670ca907fd60bc74905b0b7527f69bafc965e"
DEFAULT_ARGS = ["-language=Russian", "-quickstartup", "-host", "fc3_main", "-login", "coop1", "-coop"]

TRAMPOLINE_SRC = '''\
# generated by fc3_trampoline.py - re-executes the renamed DRM stub with extra arguments
import os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
target = os.path.join(here, "farcry3_d3d11.stub.exe")
args = __ARGS__
subprocess.run([target] + args + sys.argv[1:])
'''


def render_trampoline(args):
    # single placeholder substitution; no % formatting (avoids the double-format TypeError)
    return TRAMPOLINE_SRC.replace("__ARGS__", repr(list(args)))

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def paths(game_dir):
    bin_dir = os.path.join(game_dir, "bin")
    stub = os.path.join(bin_dir, "farcry3_d3d11.exe")
    renamed = os.path.join(bin_dir, "farcry3_d3d11.stub.exe")
    bak = os.path.join(bin_dir, "farcry3_d3d11.exe.bak")
    tramp = os.path.join(bin_dir, "farcry3_d3d11.trampoline.py")
    return bin_dir, stub, renamed, bak, tramp

def plan(mode, game_dir, args, reg_path):
    bin_dir, stub, renamed, bak, tramp = paths(game_dir)
    print("mode:            %s" % mode)
    print("game dir:        %s" % game_dir)
    print("bin dir exists:  %s" % os.path.isdir(bin_dir))
    print("stub:            %s (%s)" % (stub, "present" if os.path.isfile(stub) else "MISSING"))
    if os.path.isfile(stub):
        actual = sha256(stub)
        print("stub sha256:     %s" % actual)
        print("stub matches the known DRM stub: %s" % (actual == STUB_SHA256))
    print("renamed stub:    %s (%s)" % (renamed, "present" if os.path.isfile(renamed) else "absent"))
    print("backup:          %s (%s)" % (bak, "present" if os.path.isfile(bak) else "absent"))
    print("quick-launch args to inject: %s" % " ".join(args))
    if reg_path:
        print("reg file (written only, never applied): %s" % reg_path)
    return stub, renamed, bak, tramp

def install(game_dir, args, dry):
    stub, renamed, bak, tramp = plan("install", game_dir, args, None)
    if not os.path.isfile(stub):
        print("REFUSING: no stub to rename at %s" % stub)
        return 2
    if os.path.isfile(renamed):
        print("REFUSING: %s already exists - run `uninstall` first" % renamed)
        return 2
    digest = sha256(stub)
    if digest != STUB_SHA256:
        print("REFUSING: sha256 mismatch (expected %s, got %s)" % (STUB_SHA256, digest))
        print("   If this is intentional, pass --allow-hash-mismatch.")
        return 3
    steps = [
        ("copy   stub -> backup", lambda: shutil.copy2(stub, bak)),
        ("rename stub -> farcry3_d3d11.stub.exe", lambda: os.replace(stub, renamed)),
        ("write  trampoline -> farcry3_d3d11.exe", lambda: open(stub, "w", encoding="utf-8").write(render_trampoline(args))),
    ]
    if dry:
        for label, _ in steps:
            print("WOULD %s" % label)
        return 0
    for label, fn in steps:
        fn()
        print("OK   %s" % label)
    print("\nTEST NOW: run \"%s\" (no arguments needed; the trampoline adds them)." % stub)
    print("ROLLBACK: python fc3_trampoline.py --game-dir \"%s\" uninstall" % game_dir)
    return 0

def uninstall(game_dir, dry):
    _, stub, renamed, bak, _ = plan("uninstall", game_dir, [], None)
    if not os.path.isfile(bak):
        print("REFUSING: no backup %s - nothing to restore" % bak)
        return 2
    if sha256(bak) != STUB_SHA256:
        print("REFUSING: backup sha256 does not match the known stub")
        return 3
    steps = [("restore backup -> farcry3_d3d11.exe", lambda: shutil.copy2(bak, stub)),
             ("remove farcry3_d3d11.stub.exe", lambda: os.path.isfile(renamed) and os.remove(renamed))]
    for label, fn in steps:
        if dry:
            print("WOULD %s" % label)
        else:
            fn()
            print("OK   %s" % label)
    return 0

def reg(game_dir, out_path, dry):
    key = r"HKLM\SOFTWARE\WOW6432Node\Ubisoft\Far Cry 3"
    body = "\r\n".join([
        "Windows Registry Editor Version 5.00",
        "",
        "[%s]" % key,
        '"ExecutableName"="bin\\\\farcry3_d3d11.stub.exe"',
        "",
    ])
    print("This only WRITES a .reg file; the registry is not touched by this tool.")
    print("Apply it yourself as administrator, keep the current values first:")
    print("  reg export \"%s\" \"%s\"" % (key, os.path.join(os.path.dirname(out_path) or ".", "fc3-hklm-before.reg")))
    print("  (a backup already exists at local/registry-fc3-backup.reg in the fork repo)")
    if dry:
        print("WOULD write %s with content:\n%s" % (out_path, body))
        return 0
    with open(out_path, "w", encoding="utf-16") as f:
        f.write(body)
    print("OK   wrote %s" % out_path)
    return 0

def main():
    ap = argparse.ArgumentParser(description="Reversible quick-launch test helper for Far Cry 3 1.06.")
    ap.add_argument("action", choices=["plan", "install", "uninstall", "reg"])
    ap.add_argument("--game-dir", default="H:/FarCryCoop/TestFC3")
    ap.add_argument("--args", default=None, help="space separated args to inject (default: %s)" % " ".join(DEFAULT_ARGS))
    ap.add_argument("--reg-out", default="local/fc3-redirect-test.reg")
    ap.add_argument("--apply", action="store_true", help="actually write files (default: dry run)")
    a = ap.parse_args()
    args = a.args.split() if a.args else DEFAULT_ARGS
    dry = not a.apply
    if a.action == "plan":
        plan("plan", a.game_dir, args, None)
        return 0
    if a.action == "reg":
        return reg(a.game_dir, a.reg_out, dry)
    if a.action == "install":
        return install(a.game_dir, args, dry)
    return uninstall(a.game_dir, dry)

if __name__ == "__main__":
    sys.exit(main())
